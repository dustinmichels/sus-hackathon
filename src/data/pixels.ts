// Pixel sprites, drawn after flyer 1. One character per pixel; `.` is transparent.
// Colors are keys into `palette`.

export const palette: Record<string, string> = {
  d: '#1d381e', // vine
  g: '#2b7735', // leaf shadow
  l: '#66c536', // leaf
  y: '#a1ca21', // leaf highlight
  m: '#b3319f', // bloom
  p: '#9d2698', // bloom shadow
  r: '#e27ad6', // petal light
  w: '#fafef4', // white
  k: '#000000', // outline
};

export interface Sprite {
  width: number;
  height: number;
  /** Horizontal runs of one color, merged into a single rect each. */
  rects: { x: number; y: number; w: number; fill: string }[];
}

export function parseSprite(art: string): Sprite {
  const rows = art.trim().split('\n');
  const rects: Sprite['rects'] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const key = row[x];
      let end = x + 1;
      while (row[end] === key) end++;
      const fill = palette[key];
      if (fill) rects.push({ x, y, w: end - x, fill });
      x = end;
    }
  });
  return { width: Math.max(...rows.map((row) => row.length)), height: rows.length, rects };
}

